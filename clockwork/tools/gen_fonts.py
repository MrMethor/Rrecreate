"""Generates clockwork/dos/src/fonts.rs from DOSBox Staging's int10_memory.cpp font tables.

Usage: python clockwork/tools/gen_fonts.py reference/dosbox-staging/src/ints/int10_memory.cpp clockwork/dos/src/fonts.rs
"""

import pathlib
import re
import sys

source = pathlib.Path(sys.argv[1]).read_text(encoding="utf-8")
out_path = pathlib.Path(sys.argv[2])

tables = [
    ("int10_font_08", "FONT_8X8", 256 * 8),
    ("int10_font_14", "FONT_8X14", 256 * 14),
    ("int10_font_16", "FONT_8X16", 256 * 16),
    ("int10_font_14_alternate", "FONT_9X14_ALTERNATE", 20 * 15 + 1),
    ("int10_font_16_alternate", "FONT_9X16_ALTERNATE", 19 * 17 + 1),
]

out = [
    "//! VGA ROM fonts: 8×8, 8×14, 8×16 and the 9-dot alternate tables.",
    "//!",
    "//! Ported from DOSBox Staging `src/ints/int10_memory.cpp` (GPL-2.0-or-later), commit",
    "//! 0fdf977d9c4e41908700d7eb2255142044f881cd. Generated by clockwork/tools/gen_fonts.py; don't edit by hand.",
    "",
]

for name, rust_name, size in tables:
    match = re.search(r"uint8_t\s+" + re.escape(name) + r"\s*\[[^\]]*\]\s*=\s*\{(.*?)\};", source, re.S)
    assert match, name
    body = re.sub(r"//[^\n]*|/\*.*?\*/", "", match.group(1), flags=re.S)
    values = [int(v, 0) for v in re.findall(r"0x[0-9a-fA-F]+|\b\d+\b", body)]
    assert len(values) == size, (name, len(values), size)
    assert all(0 <= v <= 255 for v in values)
    out.append("#[rustfmt::skip]")
    out.append(f"pub static {rust_name}: [u8; {size}] = [")
    for i in range(0, size, 16):
        out.append("    " + " ".join(f"0x{v:02x}," for v in values[i : i + 16]))
    out.append("];")
    out.append("")

out_path.write_text("\n".join(out), encoding="utf-8", newline="\n")
print("wrote", out_path, sum(t[2] for t in tables), "bytes")
