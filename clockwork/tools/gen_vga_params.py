"""Generates clockwork/dos/src/vga_params.rs from DOSBox Staging's int10_vptable.cpp VGA parameter table.

Usage: python clockwork/tools/gen_vga_params.py reference/dosbox-staging/src/ints/int10_vptable.cpp clockwork/dos/src/vga_params.rs
"""

import pathlib
import re
import sys

source = pathlib.Path(sys.argv[1]).read_text(encoding="utf-8")
out_path = pathlib.Path(sys.argv[2])

ENTRIES = 0x1D
match = re.search(r"video_parameter_table_vga\s*\[[^\]]*\]\s*=\s*\{(.*?)\};", source, re.S)
assert match
body = re.sub(r"//[^\n]*|/\*.*?\*/", "", match.group(1), flags=re.S)
values = [int(v, 0) for v in re.findall(r"0x[0-9a-fA-F]+|\b\d+\b", body)]
assert len(values) == 0x40 * ENTRIES, len(values)

# DOSBox labels entries 17h-19h "mode e", "mode f" and "mode 10"; their contents are the
# 400-line text modes of the IBM VGA table order, which is what the names below follow.
NAMES = [
    "mode 0 (200 lines)", "mode 1 (200 lines)", "mode 2 (200 lines)", "mode 3 (200 lines)",
    "mode 4", "mode 5", "mode 6", "mode 7 (350 lines)",
    "reserved", "reserved", "reserved", "reserved", "reserved",
    "mode 0Dh", "mode 0Eh", "mode 0Fh (64 KB)", "mode 10h (64 KB)", "mode 0Fh", "mode 10h",
    "mode 0 (350 lines)", "mode 1 (350 lines)", "mode 2 (350 lines)", "mode 3 (350 lines)",
    "modes 0, 1 (400 lines)", "modes 2, 3 (400 lines)", "mode 7 (400 lines)",
    "mode 11h", "mode 12h", "mode 13h",
]
assert len(NAMES) == ENTRIES

out = [
    "//! The VGA BIOS video parameter table: per-mode register values the BIOS loads on a mode set.",
    "//!",
    "//! Ported from DOSBox Staging `src/ints/int10_vptable.cpp` (GPL-2.0-or-later), commit",
    "//! 0fdf977d9c4e41908700d7eb2255142044f881cd. Generated by `clockwork/tools/gen_vga_params.py`;",
    "//! don't edit by hand.",
    "//!",
    "//! Each 64-byte entry: columns, rows - 1, character height, page size (u16), sequencer",
    "//! registers 1-4, miscellaneous output, CRTC registers 0-18h, attribute registers 0-13h and",
    "//! graphics registers 0-8.",
    "",
    f"pub static VGA_PARAMETERS: [[u8; 64]; {ENTRIES}] = [",
]
for i in range(ENTRIES):
    entry = values[i * 0x40 : (i + 1) * 0x40]
    out.append(f"    // {i:02X}h: {NAMES[i]}")
    out.append("    [")
    for j in range(0, 64, 16):
        out.append("        " + " ".join(f"0x{v:02x}," for v in entry[j : j + 16]))
    out.append("    ],")
out.append("];")
out.append("")

out_path.write_text("\n".join(out), encoding="utf-8", newline="\n")
print("wrote", out_path)
